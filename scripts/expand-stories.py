def replace_text(src, sid, pid, new):
    # page("sid", "pid", "kind", "OLD"
    pat = re.compile(
        rf'(page\(\s*"{re.escape(sid)}"\s*,\s*"{re.escape(pid)}"\s*,\s*"[^"]+"\s*,\s*")([^"]*)(")',
        re.S,
    )
    m = pat.search(src)
    if not m:
        raise SystemExit(f"missing {sid}/{pid}")
    return pat.sub(lambda m: m.group(1) + new + m.group(3), src, count=1)

